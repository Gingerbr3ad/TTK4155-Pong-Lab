#include "application/hyper/hyper_mode.h"
#include "application/oled/oled_utils.h"
#include "application/oled/sprites.h"

#include <stdlib.h>

#define HYPER_TICK_HZ 94u
#define TARGET_LIFETIME (2u * HYPER_TICK_HZ)
#define TARGET_NEXT_DELAY (2u * HYPER_TICK_HZ)
#define TENSION_DECAY_TICKS 20u

static uint8_t motor_percent;
static uint8_t target_percent;
static uint8_t target_active;
static uint16_t target_remaining;
static uint16_t spawn_countdown;
static uint32_t bonus_points;
static uint8_t tension;
static uint8_t decay_ticks;
static uint8_t prev_sector = 0;
static uint16_t random_state = 0xACE1u;

static uint8_t random_byte() {
    // Haven't found a random function for the atmega (without adding large libraries), so had this generated by AI
    random_state ^= random_state << 7;
    random_state ^= random_state >> 9;
    random_state ^= random_state << 8;
    return (uint8_t)random_state;
}

static void update_spin_tension(touch_position_t touch) {
    int16_t x = touch.x;
    int16_t y = touch.y;

    uint8_t sector;

    if (abs(x) >= abs(y)) {
        if (x >= 0) {sector = 0;} // Right
        else {sector = 2;} // Left
    } else {
        if (y >= 0) {sector = 1;} // Up
        else {sector = 3;} // Down
    }

    if ((prev_sector != sector) && (tension < 99)) {
        tension += 2;
    }
    prev_sector = sector;
}

static void spawn_target() {
    target_percent = (uint8_t)(15u + random_byte() % 71u);;
    target_remaining = TARGET_LIFETIME;
    target_active = 1;
}

void hyper_mode_start() {
    motor_percent = 50;
    target_percent = 50;
    target_active = 0;
    target_remaining = 0;
    spawn_countdown = HYPER_TICK_HZ;
    bonus_points = 0;
    tension = 100;
    decay_ticks = 0;
    random_byte();
}

void hyper_mode_tick(touch_position_t touch) {
    update_spin_tension(touch);
    if (++decay_ticks >= TENSION_DECAY_TICKS) {
        decay_ticks = 0;
        if (tension-1) {--tension;}
    }
    if (target_active) {
        if (--target_remaining == 0) {
            target_active = 0;
            spawn_countdown = TARGET_NEXT_DELAY;
        }
    } else if (spawn_countdown && --spawn_countdown == 0) {
        spawn_target();
    }
}

void hyper_mode_receive_position(uint8_t percent) {
    motor_percent = percent;

    int16_t distance_to_target = (int16_t)percent - target_percent;
    if (target_active && distance_to_target >= -4 && distance_to_target <= 4) {
        target_active = 0;
        target_remaining = 0;
        spawn_countdown = TARGET_NEXT_DELAY;
        bonus_points += 100;
    }
}

uint8_t hyper_mode_tension() {return tension;}
uint16_t hyper_mode_bonus() {return bonus_points;}

void hyper_mode_draw(uint16_t score) {
    char text[11];
    framebuffer_clear();
    oled_goto_pos(2, 5);
    oled_write_string_P(PSTR("HYPER PONG"), OLED_FONT_LARGE);
    oled_goto_pos(20, 38);
    oled_write_string_P(PSTR("SCORE"), OLED_FONT_NORMAL);
    ultoa(score+bonus_points, text, 10);
    oled_goto_pos(30, 38);
    oled_write_string(text, OLED_FONT_LARGE);

    // Motor position bar
    oled_goto_pos(56, 6);
    oled_write_string_P(PSTR("|--------------------|"), OLED_FONT_SMALL);

    // Bonus target
    if (target_active) {
        oled_goto_pos(48, target_percent+10);
        oled_write_string_P(PSTR("*"), OLED_FONT_SMALL);
    }
    // Current motor position
    oled_goto_pos(56, motor_percent+10);
    oled_write_string_P(PSTR("^"), OLED_FONT_SMALL);

    // Spring meter
    if (tension < 75) {
        if (tension < 50) {
            if (tension < 25) {
                oled_goto_pos(0, 120);
                oled_draw_sprite(spring_4, SPRING_4_WIDTH, SPRING_4_HEIGHT);
                return;
            }
            oled_goto_pos(0, 120);
            oled_draw_sprite(spring_3, SPRING_3_WIDTH, SPRING_3_HEIGHT);
            return;
        }
        oled_goto_pos(0, 120);
        oled_draw_sprite(spring_2, SPRING_2_WIDTH, SPRING_2_HEIGHT);
        return;
    } 
    oled_goto_pos(0, 120);
    oled_draw_sprite(spring_1, SPRING_1_WIDTH, SPRING_1_HEIGHT);
    return;
}
